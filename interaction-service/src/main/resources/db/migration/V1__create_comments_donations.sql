CREATE TABLE comments
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    broadcast_id    BIGINT                   NOT NULL,
    author_id       BIGINT                   NOT NULL,
    author_nickname VARCHAR(20)              NOT NULL,
    content         VARCHAR(300)             NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_comments_broadcast_id ON comments (broadcast_id, id DESC);

CREATE TABLE donations
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id          VARCHAR(64)              NOT NULL,
    broadcast_id      BIGINT                   NOT NULL,
    streamer_id       BIGINT                   NOT NULL,
    streamer_nickname VARCHAR(20)              NOT NULL,
    donor_id          BIGINT                   NOT NULL,
    donor_nickname    VARCHAR(20)              NOT NULL,
    amount            BIGINT                   NOT NULL,
    message           VARCHAR(200)             NOT NULL DEFAULT '',
    status            VARCHAR(10)              NOT NULL,
    payment_key       VARCHAR(200),
    approved_at       TIMESTAMP WITH TIME ZONE,
    failure_reason    VARCHAR(200),
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    -- 같은 주문, 같은 결제가 두 번 적립되는 것을 DB 차원에서도 막는다.
    CONSTRAINT uk_donations_order_id UNIQUE (order_id),
    CONSTRAINT uk_donations_payment_key UNIQUE (payment_key),
    CONSTRAINT chk_donation_amount CHECK (amount > 0),
    CONSTRAINT chk_donation_status CHECK (status IN ('PENDING', 'DONE', 'FAILED'))
);

CREATE INDEX idx_donations_broadcast_status ON donations (broadcast_id, status, approved_at DESC);
