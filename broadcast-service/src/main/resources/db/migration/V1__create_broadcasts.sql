CREATE TABLE broadcasts
(
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id             BIGINT                   NOT NULL,
    owner_nickname       VARCHAR(20)              NOT NULL,
    title                VARCHAR(100)             NOT NULL,
    description          VARCHAR(1000)            NOT NULL DEFAULT '',
    status               VARCHAR(10)              NOT NULL,
    source_type          VARCHAR(20),
    stream_online        BOOLEAN                  NOT NULL DEFAULT FALSE,
    publish_token        VARCHAR(64),
    stream_offline_since TIMESTAMP WITH TIME ZONE,
    started_at           TIMESTAMP WITH TIME ZONE,
    ended_at             TIMESTAMP WITH TIME ZONE,
    created_at           TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at           TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT chk_broadcast_status CHECK (status IN ('READY', 'LIVE', 'ENDED'))
);

CREATE INDEX idx_broadcasts_status_created ON broadcasts (status, created_at DESC);
CREATE INDEX idx_broadcasts_owner_created ON broadcasts (owner_id, created_at DESC);

CREATE TABLE recordings
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    broadcast_id      BIGINT                   NOT NULL,
    owner_id          BIGINT                   NOT NULL,
    owner_nickname    VARCHAR(20)              NOT NULL,
    title             VARCHAR(100)             NOT NULL,
    media_path        VARCHAR(50)              NOT NULL,
    storage_location  VARCHAR(255)             NOT NULL,
    status            VARCHAR(10)              NOT NULL,
    started_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    ended_at          TIMESTAMP WITH TIME ZONE,
    duration_seconds  BIGINT                   NOT NULL DEFAULT 0,
    segment_count     INTEGER                  NOT NULL DEFAULT 0,
    last_segment_path VARCHAR(255),
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT chk_recording_status CHECK (status IN ('RECORDING', 'READY', 'FAILED'))
);

CREATE INDEX idx_recordings_media_path_status ON recordings (media_path, status);
CREATE INDEX idx_recordings_broadcast ON recordings (broadcast_id, started_at DESC);
CREATE INDEX idx_recordings_status_started ON recordings (status, started_at DESC);
